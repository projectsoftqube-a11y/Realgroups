"use client";

import { useEffect, useState } from "react";
import Image from "next/image";
import Link from "next/link";
import { usePathname } from "next/navigation";

import { Container } from "@/components/Container";
import { SiteHeader } from "@/components/SiteHeader";
import { TopBar } from "@/components/TopBar";
import { site } from "@/lib/site";

/**
 * Fixed chrome: logo on the left, with the utility row and primary navigation
 * stacked in a right-hand column. `items-center` on that pair is what keeps the
 * logo optically centred against the full height of the bar.
 *
 * `fixed` rather than `sticky` so it takes no space in the flow — hero imagery
 * still runs full-bleed from y=0 — while remaining on screen as you scroll.
 * Past the fold it condenses into a solid bar.
 */
export function SiteChrome() {
  const pathname = usePathname();
  const [scrolled, setScrolled] = useState(false);
  const [open, setOpen] = useState(false);
  const [expanded, setExpanded] = useState<string | null>(null);

  useEffect(() => {
    const onScroll = () => setScrolled(window.scrollY > 40);
    onScroll();
    window.addEventListener("scroll", onScroll, { passive: true });
    return () => window.removeEventListener("scroll", onScroll);
  }, []);

  /* Close the mobile drawer whenever the route changes. Adjusted during render
     rather than in an effect — the effect version fires a second render pass
     and trips react-hooks/set-state-in-effect. */
  const [lastPath, setLastPath] = useState(pathname);
  if (lastPath !== pathname) {
    setLastPath(pathname);
    setOpen(false);
    setExpanded(null);
  }

  // Lock body scroll while the drawer is open.
  useEffect(() => {
    document.body.style.overflow = open ? "hidden" : "";
    return () => {
      document.body.style.overflow = "";
    };
  }, [open]);

  return (
    <header
      className={`fixed inset-x-0 top-0 z-50 transition-[background-color,box-shadow,backdrop-filter,padding] duration-300 ${
        scrolled
          ? "bg-neutral-950/85 py-3 shadow-[0_8px_30px_rgba(0,0,0,0.35)] backdrop-blur-lg lg:py-4"
          : "bg-transparent py-5 lg:py-7"
      }`}
    >
      {/* Scrim for legibility over bright slides; fades out once the solid
          condensed bar takes over. */}
      <div
        className={`pointer-events-none absolute inset-x-0 top-0 h-64 bg-gradient-to-b from-black/70 via-black/30 to-transparent transition-opacity duration-300 ${
          scrolled ? "opacity-0" : "opacity-100"
        }`}
      />

      {/* Same <Container> as page content, so the logo lines up with body copy
          at every width — at 1920px a wider header would leave the logo far
          outside the 1280px content column.
          Intentionally not `relative`: the mobile drawer inside is absolutely
          positioned and should resolve against <header> so it spans the full
          viewport width and clears the header's bottom padding. */}
      <Container className="flex items-center gap-3 sm:gap-5">
        <Link href="/" aria-label={`${site.name} — home`} className="block shrink-0">
          {/* Reversed mark generated by scripts/make-logo.mjs — the supplied
              JPG had a white background baked in. */}
          <Image
            src="/images/logo-light.png"
            alt={site.name}
            width={570}
            height={315}
            priority
            quality={95}
            sizes="300px"
            className={`w-auto drop-shadow-[0_2px_10px_rgba(0,0,0,0.55)] transition-all duration-300 ${
              scrolled
                ? "h-10 sm:h-12 lg:h-[64px]"
                : "h-12 sm:h-16 lg:h-[92px]"
            }`}
          />
        </Link>

        <div className="flex min-w-0 flex-1 flex-col items-end gap-2 sm:gap-3 lg:gap-4">
          <TopBar compact={scrolled} />
          <SiteHeader
            open={open}
            onToggle={() => setOpen((v) => !v)}
            expanded={expanded}
            onExpand={setExpanded}
          />
        </div>
      </Container>
    </header>
  );
}
